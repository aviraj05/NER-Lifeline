window.setLanguage = function(lang) {
  const dict = translations[lang] || translations['en'];
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      // Check if element contains icon/spans inside, just replace text node safely
      // Or simply replace innerHTML if we format it right. We'll use textContent for safety.
      // Wait, some have spans. Let's handle nodes carefully.
      if (el.children.length === 0) {
        el.textContent = dict[key];
      } else {
        // If it has children (like the cargo icons), we update the specific text span inside
        const textSpan = el.querySelector('.i18n-text') || el;
        textSpan.textContent = dict[key];
      }
    }
  });
  
  // Save pref
  localStorage.setItem('ner_lang', lang);
};
